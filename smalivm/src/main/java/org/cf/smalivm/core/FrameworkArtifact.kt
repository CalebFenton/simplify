package org.cf.smalivm.core

import java.security.MessageDigest
import kotlinx.collections.immutable.PersistentList
import kotlinx.collections.immutable.PersistentMap
import kotlinx.collections.immutable.PersistentSet
import kotlinx.collections.immutable.persistentMapOf
import kotlinx.collections.immutable.persistentSetOf
import kotlinx.collections.immutable.toPersistentList
import kotlinx.collections.immutable.toPersistentMap
import kotlinx.collections.immutable.toPersistentSet
import com.android.tools.smali.dexlib2.AccessFlags

internal data class FrameworkClassArtifact(
    val type: String,
    val resourcePath: String,
    val sha256: String,
    val accessFlags: Int,
    val superclass: String?,
    val interfaces: PersistentList<String>,
    val methodDescriptors: PersistentSet<String>,
    val dynamicLoadingMethods: PersistentSet<String>,
)

/** Immutable index for the bundled framework resources generated by the build. */
internal class FrameworkArtifact private constructor(
    val formatVersion: Int,
    val apiLevel: Int,
    val classes: PersistentMap<String, FrameworkClassArtifact>,
) {
    fun openClassSource(type: String): ByteArray? {
        val entry = classes[type] ?: return null
        val bytes = requireNotNull(FrameworkArtifact::class.java.classLoader.getResourceAsStream(entry.resourcePath)) {
            "Framework artifact is missing ${entry.resourcePath} for $type"
        }.use { it.readBytes() }
        check(bytes.sha256() == entry.sha256) { "Framework artifact content hash mismatch for $type" }
        return bytes
    }

    companion object {
        private const val RESOURCE = "framework_catalog.tsv"
        private const val SUPPORTED_FORMAT = 1

        fun load(): FrameworkArtifact {
            val input = requireNotNull(FrameworkArtifact::class.java.classLoader.getResourceAsStream(RESOURCE)) {
                "Missing generated framework artifact index: $RESOURCE"
            }
            input.bufferedReader(Charsets.UTF_8).use { reader ->
                val header = requireNotNull(reader.readLine()) { "Framework artifact index is empty" }.split('\t')
                require(header.size == 3 && header[0] == "V") { "Invalid framework artifact header" }
                val formatVersion = header[1].toInt()
                require(formatVersion == SUPPORTED_FORMAT) {
                    "Unsupported framework artifact format $formatVersion"
                }
                val apiLevel = header[2].toInt()
                val builders = LinkedHashMap<String, FrameworkClassArtifactBuilder>()
                reader.forEachLine { line ->
                    if (line.isEmpty()) return@forEachLine
                    val fields = line.split('\t')
                    when (fields[0]) {
                        "C" -> {
                            require(fields.size == 7) { "Invalid framework class index row" }
                            val type = fields[1]
                            check(type !in builders) { "Duplicate framework class $type" }
                            builders[type] = FrameworkClassArtifactBuilder(
                                type,
                                fields[2],
                                fields[3],
                                parseAccessFlags(fields[4]),
                                fields[5].ifEmpty { null },
                                fields[6].split(',').filter(String::isNotEmpty),
                            )
                        }
                        "M" -> {
                            require(fields.size == 4) { "Invalid framework method index row" }
                            val owner = fields[1]
                            val builder = requireNotNull(builders[owner]) {
                                "Framework method index precedes its class: $owner"
                            }
                            builder.methods += fields[2]
                            if (fields[3] == "1") builder.dynamicMethods += "$owner->${fields[2]}"
                        }
                        else -> error("Unknown framework artifact row ${fields[0]}")
                    }
                }
                return FrameworkArtifact(
                    formatVersion,
                    apiLevel,
                    builders.mapValues { it.value.build() }.toPersistentMap(),
                )
            }
        }

        private fun parseAccessFlags(value: String): Int = value.split(',')
            .filter(String::isNotEmpty)
            .fold(0) { flags, name ->
                flags or requireNotNull(AccessFlags.getAccessFlag(name)) {
                    "Unknown framework class access flag $name"
                }.value
            }
    }

    private class FrameworkClassArtifactBuilder(
        private val type: String,
        private val resourcePath: String,
        private val sha256: String,
        private val accessFlags: Int,
        private val superclass: String?,
        private val interfaces: List<String>,
    ) {
        val methods: MutableSet<String> = linkedSetOf()
        val dynamicMethods: MutableSet<String> = linkedSetOf()

        fun build(): FrameworkClassArtifact = FrameworkClassArtifact(
            type,
            resourcePath,
            sha256,
            accessFlags,
            superclass,
            interfaces.toPersistentList(),
            methods.toPersistentSet(),
            dynamicMethods.toPersistentSet(),
        )
    }
}

private fun ByteArray.sha256(): String = MessageDigest.getInstance("SHA-256")
    .digest(this)
    .joinToString("") { byte -> "%02x".format(byte) }
